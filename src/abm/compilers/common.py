def pascal(name: str) -> str:
    """snake_case normalized field -> PascalCase Sentinel column."""
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def header(b, comment: str = "//") -> str:
    techs = ", ".join(f"{t.id}({t.relationship})" for t in b.atlas.techniques)
    return "\n".join([
        f"{comment} {b.id} | {b.name}",
        f"{comment} ATLAS tactics: {', '.join(b.atlas.tactics)} | techniques: {techs}",
        f"{comment} severity={b.severity.value} confidence={b.confidence.value} status={b.status.value}",
        f"{comment} GENERATED by atlas-behavior-map from {b.source_path.name if b.source_path else b.id}. Do not edit.",
    ])
