def pascal(name: str) -> str:
    """snake_case normalized field -> PascalCase Sentinel column."""
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def header(b, comment: str = "//", end: str = "") -> str:
    """Comment block identifying the behavior. `end` closes each line's comment for targets whose
    comments are delimited rather than line-based (SPL: ```text```)."""
    techs = ", ".join(f"{t.id}({t.relationship})" for t in b.atlas.techniques)
    return "\n".join(f"{comment} {text}{end}" for text in [
        f"{b.id} | {b.name}",
        f"ATLAS tactics: {', '.join(b.atlas.tactics)} | techniques: {techs}",
        f"severity={b.severity.value} confidence={b.confidence.value} status={b.status.value}",
        f"GENERATED by atlas-behavior-map from {b.source_path.name if b.source_path else b.id}. Do not edit.",
    ])


def not_expressible(b, target: str, reason: str, comment: str, end: str = "") -> str:
    """A rule file that is deliberately not a query, plus a logged warning.

    Emitted when a behavior's logic cannot be expressed faithfully in the target. Shipping an
    approximate rule would look deployed while missing detections; a stub without a query fails
    loudly wherever someone tries to load it, and the warning shows up at compile time.
    """
    log.warning("%s: %s in %s: %s", b.id, STUB_MARKER.lower(), target, reason)
    lines = [
        f"{STUB_MARKER} IN {target.upper()}: {reason}",
        f"This file intentionally contains no rule. Deploy the KQL rule (dist/kql/{b.id}.kql) or",
        f"replay exported spans with: abm replay --behavior {b.id} --fixture <spans.jsonl>",
    ]
    return "\n".join([header(b, comment, end), *(f"{comment} {t}{end}" for t in lines)]) + "\n"


def kql_table(source: str, profile: str = "default") -> str:
    if profile not in KQL_PROFILES:
        raise ValueError(f"unknown KQL profile '{profile}' (expected one of {sorted(KQL_PROFILES)})")
    default = pascal(source) + ("_CL" if profile == "sentinel" else "")
    return KQL_PROFILES[profile].get(source, default)


def sentinel_period(window_seconds: int) -> str:
    """Detection window -> Sentinel queryPeriod/queryFrequency in the Azure-Sentinel template format
    (5m, 1h, 1d). 0 means no window. Clamped to 5m..14d; seconds round up to whole minutes."""
    if window_seconds <= 0:
        return SENTINEL_DEFAULT_PERIOD
    s = min(max(window_seconds, SENTINEL_MIN_PERIOD_S), SENTINEL_MAX_PERIOD_S)
    minutes = -(-s // 60)
    if minutes % 1440 == 0:
        return f"{minutes // 1440}d"
    if minutes % 60 == 0:
        return f"{minutes // 60}h"
    return f"{minutes}m"
