log = logging.getLogger("abm.compilers")

STUB_MARKER = "NOT EXPRESSIBLE"
_STUB_LINE = re.compile(rf"^\S+ {STUB_MARKER} IN [A-Z]+: ", re.M)


def is_stub(text: str) -> bool:
    """True for output of not_expressible()."""
    return bool(_STUB_LINE.search(text))

