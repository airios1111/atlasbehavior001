"""Render docs/ocsf-mapping.md (the per-source OCSF mapping reference) from abm.ocsf.SOURCES.

    python scripts/gen_ocsf_mapping_doc.py          # rewrite docs/ocsf-mapping.md
    python scripts/gen_ocsf_mapping_doc.py --check  # exit 1 if the committed file is stale
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from abm.compilers.common import KQL_TABLES  # noqa: E402
from abm.ocsf import CLASSES, EXTENSION, OCSF_VERSION, SOURCES, mapping_rows  # noqa: E402
from abm.ocsf_schema import OcsfSchema  # noqa: E402

OUT = ROOT / "docs" / "ocsf-mapping.md"
TIER = {"core": "OCSF core", "abm": "abm ext", "unmapped": "unmapped", "alias": "alias"}


def render() -> str:
    schema = OcsfSchema.load(ROOT)
    rows = mapping_rows(schema)
    lines = [
        "# OCSF mapping reference",
        "",
        "Generated by `scripts/gen_ocsf_mapping_doc.py` from `src/abm/ocsf.py`. Do not edit by hand.",
        "",
        f"OCSF {OCSF_VERSION} core + `{EXTENSION['name']}` extension {EXTENSION['version']}. Tiers: "
        "**OCSF core** = attribute defined by OCSF (including the `ai_operation` profile objects "
        "`ai_model` and `message_context`); **abm ext** = the path goes through an attribute the "
        "abm extension adds; **unmapped** = kept in OCSF's `unmapped` object because neither the "
        "core nor an AI-specific extension object is the right home; **alias** = emitted as a copy "
        "of another field.",
        "",
        "## Summary",
        "",
        "| Source | SIEM table | OCSF class | Fields | OCSF core | abm ext | unmapped | alias |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, spec in SOURCES.items():
        c = Counter(r["tier"] for r in rows if r["source"] == name and r["class_uid"] == spec.class_uid)
        cls = f"{CLASSES[spec.class_uid][2]} ({spec.class_uid})"
        if spec.alt_classes:
            cls += " / " + ", ".join(f"{CLASSES[u][2]} ({u})" for u in spec.alt_classes)
        lines.append(f"| `{name}` | `{KQL_TABLES[name]}` | {cls} | {sum(c.values())} | {c['core']} | "
                     f"{c['abm']} | {c['unmapped']} | {c['alias']} |")
    for name, spec in SOURCES.items():
        lines += ["", f"## `{name}`", "",
                  f"Primary class: **{CLASSES[spec.class_uid][2]}** (`class_uid` {spec.class_uid})."]
        if spec.ai_role_id is not None:
            lines.append(f"Written with `message_context.ai_role_id` = {spec.ai_role_id}.")
        if spec.alt_classes:
            for u, ov in spec.alt_classes.items():
                lines.append(f"Also accepted as **{CLASSES[u][2]}** ({u}); overrides: "
                             + ", ".join(f"`{k}` → `{v}`" for k, v in ov.items()) + ".")
        lines += ["", "| Normalized field | OCSF path | Tier |", "|---|---|---|",
                  "| `timestamp` | `time_dt` (else `time`, epoch ms) | OCSF core |"]
        for r in rows:
            if r["source"] == name and r["class_uid"] == spec.class_uid:
                lines.append(f"| `{r['field']}` | `{r['path']}` | {TIER[r['tier']]} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    body = render()
    if a.check:
        cur = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.is_file() else ""
        ok = cur == body
        print("docs/ocsf-mapping.md up to date" if ok else "stale: run python scripts/gen_ocsf_mapping_doc.py")
        return 0 if ok else 1
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
