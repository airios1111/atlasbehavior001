"""Render the behavior pack (scripts/behavior_pack/) into behaviors/ and tests/fixtures/pack/.

    python scripts/gen_behavior_pack.py            # fixtures always; YAML only where missing
    python scripts/gen_behavior_pack.py --force    # also overwrite existing pack YAML

Once written, the YAML under behaviors/ is the contract and may be edited by hand. Re-running without
--force keeps those edits and only refreshes fixtures. Every pack behavior ships at status `test`;
promote to `stable` after reviewing the compiled queries against real telemetry.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml
from behavior_pack import SPECS

from abm.catalog import AtlasCatalog

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests" / "fixtures" / "pack"
HEADER = "# Generated by scripts/gen_behavior_pack.py (behavior pack). Safe to edit by hand.\n"


class _Folded(str):
    pass


class _Dumper(yaml.SafeDumper):
    pass


def _leaf(v) -> bool:
    return not isinstance(v, (dict, list))


def _repr_list(d, data):
    flow = all(_leaf(x) for x in data) and len(repr(data)) < 90
    return d.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=flow)


def _repr_dict(d, data):
    flow = all(_leaf(v) for v in data.values()) and len(repr(data)) < 90
    return d.represent_mapping("tag:yaml.org,2002:map", data.items(), flow_style=flow)


_Dumper.add_representer(list, _repr_list)
_Dumper.add_representer(dict, _repr_dict)
_Dumper.add_representer(_Folded, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", str(s), style=">"))


def stem(behavior_id: str) -> str:
    return behavior_id.removeprefix("BHV-").replace("-", "").lower()  # BHV-PI-003 -> pi003


def render(spec: dict, catalog: AtlasCatalog) -> str:
    tactics = spec["tactics"] or list(catalog.tactics_for(spec["primary"]))
    parent = ".".join(spec["primary"].split(".")[:2])
    fx = f"tests/fixtures/pack/{stem(spec['id'])}"
    doc: dict = {
        "id": spec["id"], "name": spec["name"], "status": "test",
        "severity": spec["severity"], "confidence": spec["confidence"],
        "description": _Folded(spec["description"]),
        "atlas": {"tactics": tactics, "techniques": spec["techniques"]},
    }
    if spec["attack_bridge"]:
        doc["attack_bridge"] = spec["attack_bridge"]
    doc["telemetry"] = {"required": [{"source": spec["source"], "fields": spec["fields"]}]}
    doc["detection"] = spec["detection"]
    doc["countermeasures"] = {"mitigations": spec["mitigations"], "response": spec["response"]}
    doc["tests"] = [{"fixture": f"{fx}_attack.jsonl", "expect": "alert"},
                    {"fixture": f"{fx}_benign.jsonl", "expect": "no_alert"}]
    doc["references"] = [f"https://atlas.mitre.org/techniques/{parent}"]
    return HEADER + yaml.dump(doc, Dumper=_Dumper, sort_keys=False, width=110, allow_unicode=True)


def write_jsonl(path: Path, rows: list[dict]) -> None:
    path.write_text("\n".join(json.dumps(r, separators=(",", ":"), ensure_ascii=False) for r in rows) + "\n",
                    encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--force", action="store_true", help="overwrite existing pack YAML files")
    args = ap.parse_args()

    ids = [s["id"] for s in SPECS]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        print(f"duplicate ids in specs: {sorted(dupes)}", file=sys.stderr)
        return 1

    catalog = AtlasCatalog.load(ROOT / "atlas" / "catalog.yaml")
    FIXTURES.mkdir(parents=True, exist_ok=True)
    written = kept = 0
    for spec in SPECS:
        write_jsonl(FIXTURES / f"{stem(spec['id'])}_attack.jsonl", spec["attack"])
        write_jsonl(FIXTURES / f"{stem(spec['id'])}_benign.jsonl", spec["benign"])
        dest = ROOT / "behaviors" / spec["category"] / f"{spec['id']}.yaml"
        if dest.exists() and not args.force:
            kept += 1
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(render(spec, catalog), encoding="utf-8")
        written += 1
    print(f"{len(SPECS)} pack behaviors: {written} YAML written, {kept} kept; "
          f"{2 * len(SPECS)} fixtures -> {FIXTURES.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
